use crate::dimensionality;
use cobia::*;

/// A scalar real CAPE-OPEN parameter for energy and information streams.
///
/// Implements `ICapeIdentification`, `ICapeParameter`, and
/// `ICapeRealParameter`. The dimensionality vector is converted to a
/// human-readable unit string on construction via [`dimensionality::as_string`].
#[cape_object_implementation(
		interfaces = {
			cape_open_1_2::ICapeIdentification,
			cape_open_1_2::ICapeParameter,
			cape_open_1_2::ICapeRealParameter,
		},
        new_arguments = {name,description,is_input,default_value,min_value,max_value,dimensionality},
  )]
pub(crate) struct RealParameter {
    /// Parameter name, adapted from parameter specification items on the energy or information port.
    pub(crate) name: String,
    /// Parameter description, adapted from parameter specification items on the energy or information port.
    description: String,
    /// `true` for input parameter (CapeInput); `false` for output parameter (CapeOutput).
    is_input: bool,
    /// CAPE-OPEN dimensionality exponent vector in `CapeDimensionality` order.
    dimensionality: Vec<f64>,
    /// Unit-of-measure string derived from `dimensionality` via [`dimensionality::as_string`]. Empty for dimensionless parameters.
    pub(crate) unit_of_measure: String,
    /// Cached postfix appended to values in error messages (e.g. `" Pa"` or `""` when dimensionless).
    postfix: String,
    /// Current parameter value in SI base units. `NaN` signals an unset value.
    pub(crate) value: f64,
    /// Optional default value. `None` when no default was specified by the property package.
    default_value: Option<f64>,
    /// Optional lower bound. `None` when unconstrained.
    min_value: Option<f64>,
    /// Optional upper bound. `None` when unconstrained.
    max_value: Option<f64>,
    /// Current validation status. Initially `CapeNotValidated`, updated by calls to `validate()`.
    pub(crate) validation_status: cape_open_1_2::CapeValidationStatus,
}

impl RealParameter {
    /// Constructs a [`RealParameter`] and computes derived display fields.
    ///
    /// # Parameters
    /// - `name`: Parameter name.
    /// - `description`: Human-readable description.
    /// - `is_input`: `true` for input, `false` for output.
    /// - `default_value`: Optional default; used as the initial `value` when
    ///   present, otherwise `value` starts as `NaN`.
    /// - `min_value`: Optional lower bound for validation.
    /// - `max_value`: Optional upper bound for validation.
    /// - `dimensionality`: CAPE-OPEN dimensionality exponent vector.
    ///
    /// # Returns
    /// A fully initialised [`RealParameter`] with `CapeNotValidated` status.
    pub fn new(
        name: String,
        description: String,
        is_input: bool,
        default_value: Option<f64>,
        min_value: Option<f64>,
        max_value: Option<f64>,
        dimensionality: Vec<f64>,
    ) -> Self {
        let unit_of_measure = dimensionality::as_string(&dimensionality);
        let postfix = if unit_of_measure.is_empty() {
            "".to_string()
        } else {
            format!(" {}", unit_of_measure)
        };
        Self {
            name,
            description,
            is_input,
            dimensionality,
            unit_of_measure,
            postfix,
            value: default_value.unwrap_or(f64::NAN),
            default_value,
            min_value,
            max_value,
            validation_status: cape_open_1_2::CapeValidationStatus::CapeNotValidated,
            cobia_object_data: Default::default(), //Generated by cape_object_implementation, set to default
        }
    }
    /// Checks whether `value` satisfies the parameter constraints.
    ///
    /// # Parameters
    /// - `value`: The candidate value to check.
    ///
    /// # Returns
    /// - `Ok(())`: Value is finite and within `[min_value, max_value]`.
    /// - `Err(message)`: Human-readable description of why validation failed
    ///   (NaN, below minimum, or above maximum). The message includes the unit
    ///   postfix for readability.
    pub fn validate_value(&self, value: f64) -> Result<(), String> {
        if f64::is_nan(value) {
            Err("Value is UNDEFINED".to_string())
        } else {
            if let Some(min) = self.min_value
                && !f64::is_nan(min) && value < min {
                    return Err(format!(
                        "Value of {}{} is below the minimum of {}{}",
                        value, self.postfix, min, self.postfix
                    ));
                }
            if let Some(max) = self.max_value
                && !f64::is_nan(max) && value > max {
                    return Err(format!(
                        "Value {}{} is above the maximum of {}{}",
                        value, self.postfix, max, self.postfix
                    ));
                }
            Ok(())
        }
    }
}

impl std::fmt::Display for RealParameter {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "Parameter \"{}\"", self.name)
    }
}

impl cape_open_1_2::ICapeIdentification for RealParameter {
    fn set_component_name(&mut self, _name: &CapeStringIn) -> Result<(), COBIAError> {
        Err(COBIAError::Code(COBIAERR_DENIED))
    }

    fn set_component_description(&mut self, _desc: &CapeStringIn) -> Result<(), COBIAError> {
        Err(COBIAError::Code(COBIAERR_DENIED))
    }

    fn get_component_name(&mut self, name: &mut CapeStringOut) -> Result<(), COBIAError> {
        name.set_string(&self.name)
    }

    fn get_component_description(&mut self, desc: &mut CapeStringOut) -> Result<(), COBIAError> {
        desc.set_string(&self.description)
    }
}

impl cape_open_1_2::ICapeParameter for RealParameter {
    fn get_val_status(&mut self) -> Result<cape_open_1_2::CapeValidationStatus, COBIAError> {
        Ok(self.validation_status)
    }

    fn get_mode(&mut self) -> Result<cape_open_1_2::CapeParamMode, COBIAError> {
        if self.is_input {
            Ok(cape_open_1_2::CapeParamMode::CapeInput)
        } else {
            Ok(cape_open_1_2::CapeParamMode::CapeOutput)
        }
    }

    fn get_type(&mut self) -> Result<cape_open_1_2::CapeParamType, COBIAError> {
        Ok(cape_open_1_2::CapeParamType::CapeParameterReal)
    }

    fn validate(&mut self, message: &mut CapeStringOut) -> Result<CapeBoolean, COBIAError> {
        cape_open_1_2::ICapeRealParameter::validate(self, self.value, message)
    }

    fn reset(&mut self) -> Result<(), COBIAError> {
        if !self.is_input {
            return Err(COBIAError::Code(COBIAERR_DENIED));
        }
        self.value = self.default_value.unwrap_or(f64::NAN);
        self.validation_status = cape_open_1_2::CapeValidationStatus::CapeNotValidated;
        Ok(())
    }
}

impl cape_open_1_2::ICapeRealParameter for RealParameter {
    fn get_value(&mut self) -> Result<CapeReal, COBIAError> {
        Ok(self.value)
    }

    fn set_value(&mut self, value: CapeReal) -> Result<(), COBIAError> {
        if !self.is_input {
            return Err(COBIAError::Code(COBIAERR_DENIED));
        }
        self.value = value;
        self.validation_status = cape_open_1_2::CapeValidationStatus::CapeNotValidated;
        Ok(())
    }

    fn get_default_value(&mut self) -> Result<CapeReal, COBIAError> {
        match self.default_value {
            Some(v) => Ok(v),
            None => Err(COBIAError::Code(COBIAERR_NOSUCHITEM)),
        }
    }

    fn get_lower_bound(&mut self) -> Result<CapeReal, COBIAError> {
        match self.min_value {
            Some(v) => Ok(v),
            None => Err(COBIAError::Code(COBIAERR_NOSUCHITEM)),
        }
    }

    fn get_upper_bound(&mut self) -> Result<CapeReal, COBIAError> {
        match self.max_value {
            Some(v) => Ok(v),
            None => Err(COBIAError::Code(COBIAERR_NOSUCHITEM)),
        }
    }

    fn get_dimensionality(
        &mut self,
        dimensionality: &mut CapeArrayRealOut,
    ) -> Result<(), COBIAError> {
        dimensionality.put_array(&self.dimensionality)
    }

    fn validate(
        &mut self,
        value: CapeReal,
        message: &mut CapeStringOut,
    ) -> Result<CapeBoolean, COBIAError> {
        //this implementation does not allow for missing values
        match self.validate_value(value) {
            Ok(_) => Ok(true as CapeBoolean),
            Err(e) => {
                message.set_string(&e)?;
                Ok(false as CapeBoolean)
            }
        }
    }
}
