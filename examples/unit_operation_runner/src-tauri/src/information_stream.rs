use crate::{
    real_parameter::RealParameter,
    stream_specification::{StreamSpecification, StreamSpecificationType},
};
use cobia::{prelude::*, *};

/// Runtime representation of an information or energy stream connected to a unit port.
///
/// The stream owns a list of real CAPE parameters discovered from the connected
/// port and tracks user-entered specifications that are applied onto those
/// parameters. Stream completion/validation status is exposed via
/// [`Self::is_specified`] and [`Self::specification_error`].
#[cape_object_implementation(
		interfaces={ 
			cape_open_1_2::ICapeIdentification,
			cape_open_1_2::ICapeCollection<cape_open_1_2::CapeParameter>,
		},
  )]
pub(crate) struct InformationStream {
    /// User-friendly name and description for the stream, initialized from port info.
    pub(crate) name: String,
    /// Description of the stream, initialized from port info.
    pub(crate) description: String,
    /// List of parameters associated with the stream, initialized from the connected port.
    parameters: Vec<cape_open_1_2::CapeParameter>,
    /// Map from parameter names to their index in the `parameters` vector for quick lookup.
    parameter_name_map: cobia::CapeOpenMap<usize>,
    /// Whether the stream is a feed stream (true) or product stream (false), used to control mutability of specifications.
    pub(crate) is_feed: bool,
    /// Whether the stream is an energy stream (true) or information stream (false), used to control display and validation of parameters.
    pub(crate) is_energy: bool,
    /// Whether the stream is fully specified
    pub(crate) is_specified: bool,
    /// if specification fails, the reason for it
    pub(crate) specification_error: Option<String>,
    /// The canonical list of user-entered specifications that are applied to parameters
    specifications: Vec<StreamSpecification>,
}

impl std::default::Default for InformationStream {
    fn default() -> Self {
        Self {
            name: String::new(),
            description: String::new(),
            parameters: Vec::new(),
            parameter_name_map: cobia::CapeOpenMap::new(),
            is_feed: false,
            is_energy: false,
            cobia_object_data: Default::default(), //Generated by cape_object_implementation, set to default
            is_specified: false,
            specification_error: None,
            specifications: Vec::new(),
        }
    }
}

impl InformationStream {
    /// Returns an iterator over the stream parameters.
    pub fn iter(&self) -> impl Iterator<Item = &cape_open_1_2::CapeParameter> {
        self.parameters.iter()
    }

    /// Adds, updates, or removes a single specification entry.
    ///
    /// Behavior:
    /// - Empty/whitespace `value` removes an existing specification for `spec_type`.
    /// - Non-empty `value` must parse as `f64`; parse errors return `false`.
    /// - When a change is made, all specifications are re-applied.
    ///
    /// # Parameters
    /// - `spec_type`: The type of specification to add, update, or remove.
    /// - `value`: The string value of the specification; empty or whitespace to remove.
    ///
    /// #Returns
    /// `true` if the specification set changed, otherwise `false`.
    pub fn specify(&mut self, spec_type: StreamSpecificationType, value: &str) -> bool {
        //find if the specification is already there
        let mut need_update = false;
        let spec_index = self
            .specifications
            .iter()
            .position(|s| s.specification_type == spec_type);
        if value.trim().is_empty() {
            match spec_index {
                Some(i) => {
                    //remove specification
                    self.specifications.remove(i);
                    need_update = true;
                }
                None => {
                    //nothing to remove
                }
            };
        } else {
            //parse the value
            let value: f64 = match value.parse() {
                Ok(v) => v,
                Err(_) => {
                    return false;
                }
            };
            match spec_index {
                Some(i) => {
                    //update existing specification
                    if self.specifications[i].value != value {
                        need_update = true;
                        self.specifications[i].value = value;
                    }
                }
                None => {
                    //insert new specification
                    self.specifications.push(StreamSpecification {
                        specification_type: spec_type,
                        value,
                    });
                    need_update = true;
                }
            }
        }
        if need_update {
            self.apply_specifications();
        }
        need_update
    }

    /// Returns the current list of stream specifications.
    pub fn get_specifications(&self) -> &Vec<StreamSpecification> {
        &self.specifications
    }

    /// Replaces the full specification set and re-applies it to parameters.
    pub fn set_specifications(&mut self, specs: Vec<StreamSpecification>) {
        self.specifications = specs;
        self.apply_specifications();
    }

    /// Applies current specifications to parameters and recomputes stream validity.
    ///
    /// This method resets all parameter values to unspecified (`NaN`), applies
    /// supported specifications, removes invalid/unresolvable specifications, and
    /// validates resulting parameter values. On failure, [`Self::specification_error`]
    /// contains a human-readable reason.
    pub fn apply_specifications(&mut self) {
        self.specification_error = None;
        self.is_specified = false;
        self.specification_error = None;
        self.is_specified = false;
        for par in self.parameters.iter_mut() {
            let parameter = unsafe { RealParameter::borrow_mut(par) };
            parameter.value = f64::NAN; //reset all parameters to unspecified
            parameter.validation_status = cape_open_1_2::CapeValidationStatus::CapeNotValidated;
        }
        //process spec and set
        self.specifications.retain(|spec| {
            match &spec.specification_type {
                StreamSpecificationType::ParameterValue(name) => {
                    //find parameter by name
                    let name_str = CapeStringImpl::from_string(name);
                    match self.parameter_name_map.get(&name_str) {
                        Some(index) => {
                            unsafe { RealParameter::borrow_mut(&self.parameters[*index]) }.value =
                                spec.value;
                            true
                        }
                        None => false,
                    }
                }
                _ => {
                    //invalid spec
                    false
                }
            }
        });
        //check if complete and determine error
        for par in self.parameters.iter() {
            let parameter = unsafe { RealParameter::borrow(par) };
            if f64::is_nan(parameter.value) {
                self.specification_error =
                    Some(format!("Parameter {} is not specified", parameter.name));
                self.is_specified = false;
                return;
            } else {
                match parameter.validate_value(parameter.value) {
                    Ok(_) => {}
                    Err(msg) => {
                        self.specification_error =
                            Some(format!("Invalid value for {}: {}", parameter.name, msg));
                        self.is_specified = false;
                        return;
                    }
                }
            }
        }
        self.is_specified = true;
    }

    /// Rebuilds stream parameters from a CAPE unit port definition.
    ///
    /// The method reads parameter specifications from `port`, recreates internal
    /// parameter objects, and validates constraints specific to energy ports.
    ///
    /// Energy stream rules enforced here:
    /// - Parameter names are restricted to `work`, `temperatureLow`,
    ///   `temperatureHigh`, and `axisFrequency` (case-insensitive input).
    /// - Dimensionality must match the expected base-dimension exponents.
    /// - A `work` parameter is mandatory.
    ///
    /// Existing values and maps are replaced, then specifications are re-applied.
    /// Returns a descriptive error if any CAPE call fails or validation fails.
    ///
    /// # Parameters
    /// - `port`: The CAPE unit port object to read parameter specifications from.
    /// - `is_feed`: Whether the port is a feed (true) or product (false) port, used for error messages and mutability rules.
    /// - `is_energy`: Whether the port is an energy stream (true) or information stream (false), used for validation rules.
    /// - `name`: The name of the port, used for error messages.
    ///
    /// # Returns
    /// `Ok(())` on success, or an error message on failure.
    pub fn update_from_port(
        &mut self,
        port: &cape_open_1_2::CapeUnitPort,
        is_feed: bool,
        is_energy: bool,
        name: &CapeStringImpl,
    ) -> Result<(), Box<dyn std::error::Error>> {
        self.name = format!(
            "{} stream connected to {} port {}",
            if is_energy { "Energy" } else { "Information" },
            if is_feed { "feed" } else { "product" },
            name
        );
        //update parameters from port
        self.parameter_name_map.clear();
        self.parameters.clear();
        self.is_specified = false;
        //get the collection of parameter specs from the port
        let parameter_spec_collection =
            match cape_open_1_2::CapeCollection::<CapeObject>::from_object(port) {
                Ok(collection) => collection,
                Err(_) => {
                    return Err(format!(
                        "Cannot obtain parameter specifications from {} {} port {}",
                        if is_energy { "Energy" } else { "Information" },
                        if is_feed { "feed" } else { "product" },
                        name
                    )
                    .into());
                }
            };
        //iterate through the parameters and add them to the stream
        let mut has_work = false;
        for par_spec in parameter_spec_collection {
            //get name
            let iden = match cape_open_1_2::CapeIdentification::from_object(&par_spec) {
                Ok(iden) => iden,
                Err(e) => {
                    return Err(format!("Cannot obtain parameter identification for a parameter specification on {} {} port {}: {}", if is_energy {"Energy"} else {"Information"}, if is_feed { "feed" } else { "product" }, name, e).into());
                }
            };
            let mut parameter_name = CapeStringImpl::new();
            match iden.get_component_name(&mut parameter_name) {
                Ok(_) => {}
                Err(e) => {
                    return Err(format!("Cannot obtain parameter name for a parameter specification on {} {} port {}: {}", if is_energy {"Energy"} else {"Information"}, if is_feed { "feed" } else { "product" }, name, e).into());
                }
            };
            let mut par_name: String = parameter_name.to_string();
            let mut par_desc = CapeStringImpl::new();
            let _ = iden.get_component_description(&mut par_desc);
            let parameter_spec = match cape_open_1_2::CapeParameterSpecification::from_object(
                &par_spec,
            ) {
                Ok(spec) => spec,
                Err(e) => {
                    return Err(format!(
                        "Cannot obtain parameter specification for {} {} port {} parameter {}: {}",
                        if is_energy { "Energy" } else { "Information" },
                        if is_feed { "feed" } else { "product" },
                        name,
                        par_name,
                        e
                    )
                    .into());
                }
            };
            match parameter_spec.get_type() {
                Ok(par_type) => match par_type {
                    cape_open_1_2::CapeParamType::CapeParameterReal => {}
                    _ => {
                        return Err(format!("Unsupported parameter type for {} {} port {} parameter {}: only real parameters are supported", if is_energy {"Energy"} else {"Information"}, if is_feed { "feed" } else { "product" }, name, par_name).into());
                    }
                },
                Err(e) => {
                    return Err(format!(
                        "Cannot obtain parameter {} type for {} {} port {} parameter {}: {}",
                        par_name,
                        if is_energy { "Energy" } else { "Information" },
                        if is_feed { "feed" } else { "product" },
                        name,
                        par_name,
                        e
                    )
                    .into());
                }
            };
            let real_par_spec = match cape_open_1_2::CapeRealParameterSpecification::from_object(
                &par_spec,
            ) {
                Ok(spec) => spec,
                Err(e) => {
                    return Err(format!("Cannot get real parameter specification for paremeter {} of {} {} port {} parameter {}: {}", par_name, if is_energy {"Energy"} else {"Information"}, if is_feed { "feed" } else { "product" }, name, par_name, e).into());
                }
            };
            let mut default_value = None;
            if let Ok(v) = real_par_spec.get_default_value()
                && !v.is_nan() {
                    default_value = Some(v);
                };
            let mut lower_bound = None;
            if let Ok(v) = real_par_spec.get_lower_bound()
                && !v.is_nan() {
                    lower_bound = Some(v);
                };
            let mut upper_bound = None;
            if let Ok(v) = real_par_spec.get_upper_bound()
                && !v.is_nan() {
                    upper_bound = Some(v);
                };
            let mut dimensionality = CapeArrayRealVec::new();
            match real_par_spec.get_dimensionality(&mut dimensionality) {
                Ok(_) => {}
                Err(e) => {
                    return Err(format!("Cannot get dimensionality for parameter {} of {} {} port {} parameter {}: {}", par_name, if is_energy {"Energy"} else {"Information"}, if is_feed { "feed" } else { "product" }, name, par_name, e).into());
                }
            };
            if dimensionality.size() > {
                cape_open_1_2::CapeDimensionality::CapeDimensionalityLength as usize
            } {
                return Err(format!("Too many dimensions for parameter {} of {} {} port {} parameter {}: maximum dimensionality vector length is {}, got {}", par_name, if is_energy {"Energy"} else {"Information"}, if is_feed { "feed" } else { "product" }, name, par_name, cape_open_1_2::CapeDimensionality::CapeDimensionalityLength,dimensionality.size()).into());
            }
            if is_energy {
                //check parameter is ok and normalize parameter name character case
                let mut expected_dim =
                    [0.0; cape_open_1_2::CapeDimensionality::CapeDimensionalityLength as usize];
                match par_name.to_lowercase().as_str() {
                    "work" => {
                        par_name = "work".to_string();
                        expected_dim[cape_open_1_2::CapeDimensionality::CapeKilogram as usize] =
                            1.0;
                        expected_dim[cape_open_1_2::CapeDimensionality::CapeMeter as usize] = 2.0;
                        expected_dim[cape_open_1_2::CapeDimensionality::CapeSecond as usize] = -3.0;
                        has_work = true;
                    }
                    "temperaturelow" => {
                        par_name = "temperatureLow".to_string();
                        expected_dim[cape_open_1_2::CapeDimensionality::CapeKelvin as usize] = 1.0;
                    }
                    "temperaturehigh" => {
                        par_name = "temperatureHigh".to_string();
                        expected_dim[cape_open_1_2::CapeDimensionality::CapeKelvin as usize] = 1.0;
                    }
                    "axisfrequency" => {
                        par_name = "axisFrequency".to_string();
                        expected_dim[cape_open_1_2::CapeDimensionality::CapeSecond as usize] = -1.0;
                    }
                    _ => {
                        return Err(format!("Unsupported parameter name {} for energy {} port {}: only work, temperatureLow, temperatureHigh, and axisFrequency are valid", par_name, if is_feed { "feed" } else { "product" }, name).into());
                    }
                };
                //check dimensionality matches expected dimensionality for energy parameters
                for i in 0..dimensionality.size() {
                    if f64::abs(dimensionality[i] - expected_dim[i]) > 1e-6 {
                        return Err(format!("Invalid dimensionality for parameter {} of {} energy port {}: expected dimension {} to have exponent {}, got {}", par_name,  if is_feed { "feed" } else { "product" }, name, {cape_open_1_2::CapeDimensionality::CapeDimensionalityLength}, expected_dim[i], dimensionality[i]).into());
                    }
                }
            }
            //add parameter
            let par: CapeObject = RealParameter::create(
                par_name,
                par_desc.to_string(),
                !is_feed,
                default_value,
                lower_bound,
                upper_bound,
                dimensionality.into_vec(),
            );
            let index = self.parameters.len();
            self.parameters
                .push(cape_open_1_2::CapeParameter::from_object(&par).unwrap());
            self.parameter_name_map
                .insert_from_cape_string(&parameter_name, index);
        }
        if is_energy && !has_work {
            return Err(format!(
                "Energy {} port {} must have a parameter named work/[W]",
                if is_feed { "feed" } else { "product" },
                name
            )
            .into());
        }
        //update
        self.apply_specifications();
        Ok(())
    }

    /// Clears all runtime parameter values and validation state.
    ///
    /// This does not remove parameter definitions or specification entries.
    pub fn clear_values(&mut self) {
        for par in self.parameters.iter_mut() {
            let parameter = unsafe { RealParameter::borrow_mut(par) };
            parameter.value = f64::NAN; //reset all parameters to unspecified
            parameter.validation_status = cape_open_1_2::CapeValidationStatus::CapeNotValidated;
        }
        self.is_specified = false;
        self.specification_error = None;
    }
}

impl std::fmt::Display for InformationStream {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "{} stream connected to {} port {}",
            if self.is_energy {
                "Energy"
            } else {
                "Information"
            },
            if self.is_feed { "feed" } else { "product" },
            self.name
        )
    }
}

impl cape_open_1_2::ICapeIdentification for InformationStream {
    fn get_component_name(&mut self, name: &mut CapeStringOut) -> Result<(), COBIAError> {
        name.set_string(&self.name)
    }

    fn get_component_description(
        &mut self,
        description: &mut CapeStringOut,
    ) -> Result<(), COBIAError> {
        description.set_string(&self.description)
    }

    fn set_component_name(&mut self, _name: &CapeStringIn) -> Result<(), COBIAError> {
        Err(cobia::COBIAError::Code(cobia::COBIAERR_DENIED))
    }

    fn set_component_description(&mut self, _desc: &CapeStringIn) -> Result<(), COBIAError> {
        Err(cobia::COBIAError::Code(cobia::COBIAERR_DENIED))
    }
}

impl cape_open_1_2::ICapeCollection<cape_open_1_2::CapeParameter> for InformationStream {
    fn item_by_index(
        &mut self,
        index: CapeInteger,
    ) -> Result<cape_open_1_2::CapeParameter, COBIAError> {
        if index < 0 || index >= self.parameters.len() as CapeInteger {
            Err(cobia::COBIAError::Code(cobia::COBIAERR_NOSUCHITEM))
        } else {
            Ok(self.parameters[index as usize].clone())
        }
    }

    fn item_by_name(
        &mut self,
        name: &CapeStringIn,
    ) -> Result<cape_open_1_2::CapeParameter, COBIAError> {
        let parameter_index = self
            .parameter_name_map
            .get(name)
            .ok_or(cobia::COBIAError::Code(cobia::COBIAERR_NOSUCHITEM))?;
        Ok(self.parameters[*parameter_index].clone())
    }

    fn get_count(&mut self) -> Result<CapeInteger, COBIAError> {
        Ok(self.parameters.len() as CapeInteger)
    }
}
